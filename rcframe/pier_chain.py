NODE = {n[0]: dict(id=n[0], c=n[1], lane=n[2], kind=n[3], label=n[4], codes=n[5], flags=n[6], desc=n[7]) for n in NODES}
NODE_IDS = [n[0] for n in NODES]


def flat(text):
    return text.replace("\n", "")


def topo_order():
    """矢印に沿った順番。循環があれば例外."""
    children = {}
    indeg = {n: 0 for n in NODE_IDS}
    for s, t, k in EDGES:
        children.setdefault(s, []).append(t)
        indeg[t] += 1
    order, st = [], [n for n in NODE_IDS if indeg[n] == 0]
    while st:
        v = st.pop(0)
        order.append(v)
        for c in children.get(v, []):
            indeg[c] -= 1
            if indeg[c] == 0:
                st.append(c)
    if len(order) != len(NODE_IDS):
        raise ValueError("変状連鎖に循環があります")
    return order
